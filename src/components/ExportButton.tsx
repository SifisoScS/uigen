/** Root-level config files stay flat; everything else goes under src/ */
const ROOT_FILES = new Set([
  "package.json",
  "tsconfig.json",
  "tsconfig.base.json",
  "tailwind.config.ts",
  "tailwind.config.js",
  "next.config.ts",
  "next.config.js",
  "postcss.config.js",
  "postcss.config.mjs",
  ".eslintrc.json",
  ".gitignore",
  "README.md",
]);

function virtualPathToZipName(virtualPath: string): string {
  const stripped = virtualPath.replace(/^\//, "");
  return ROOT_FILES.has(stripped) ? stripped : `src/${stripped}`;
}

function sanitize(name: string): string {
  return (
    name
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "uigen-export"
  );
}

/** Build the client-zip file-entry array from a map of virtual-path → content */
function buildFileEntries(
  files: Map<string, string>,
  includeBoilerplate: boolean
): Array<{ name: string; lastModified: Date; input: string }> {
  const now = new Date();
  const usedNames = new Set<string>();
  const entries: Array<{ name: string; lastModified: Date; input: string }> =
    [];

  for (const [virtualPath, content] of files) {
    const name = virtualPathToZipName(virtualPath);
    usedNames.add(name);
    entries.push({ name, lastModified: now, input: content });
  }

  if (includeBoilerplate) {
    for (const [filename, content] of Object.entries(BOILERPLATE)) {
      // Boilerplate never overwrites user files
      if (!usedNames.has(filename)) {
        entries.push({ name: filename, lastModified: now, input: content });
      }
    }
  }

  return entries;
}

/** Trigger a browser download from a Blob */
function triggerDownload(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  // Delay revoke so browser has time to begin download
  setTimeout(() => URL.revokeObjectURL(url), 10_000);
}

