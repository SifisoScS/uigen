interface ExportButtonProps {
  projectName?: string;
}

export function ExportButton({ projectName }: ExportButtonProps) {
  const { getAllFiles, selectedFile } = useFileSystem();
  const [loading, setLoading] = useState(false);

  const baseName = sanitize(projectName ?? "uigen-export");

  async function handleExport(mode: "current" | "full") {
    if (loading) return;

    const allFiles = getAllFiles();

    if (allFiles.size === 0) {
      toast.error("Nothing to export — the project has no files yet.");
      return;
    }

    // Warn on large projects (rough threshold: >50 files or >500 kB total)
    const totalBytes = [...allFiles.values()].reduce(
      (sum, c) => sum + c.length,
      0
    );
    if (allFiles.size > 50 || totalBytes > 500_000) {
      toast.warning(
        "Large project — ZIP generation may be slow in the browser.",
        { duration: 3000 }
      );
    }

    if (mode === "current") {
      const activeFile = selectedFile;
      if (!activeFile) {
        toast.error("No file is currently selected.");
        return;
      }

      // Include the active file + everything in its top-level directory
      const topDir = "/" + activeFile.split("/").filter(Boolean)[0];
      const subset = new Map<string, string>();
      for (const [path, content] of allFiles) {
        if (
          path === activeFile ||
          path.startsWith(topDir + "/") ||
          path === topDir
        ) {
          subset.set(path, content);
        }
      }

      if (subset.size === 0) {
        toast.error("Could not determine the active file subset.");
        return;
      }

      setLoading(true);
      try {
        const entries = buildFileEntries(subset, false);
        const blob = await downloadZip(entries).blob();
        const zipName =
          sanitize(
            activeFile.split("/").filter(Boolean).pop() ?? "component"
          ) + ".zip";
        triggerDownload(blob, zipName);
        toast.success(
          `Exported "${zipName}" — ${subset.size} file${subset.size === 1 ? "" : "s"}`
        );
      } catch (err) {
        console.error("[ExportButton] current export failed", err);
        toast.error("Export failed. Please try again.");
      } finally {
        setLoading(false);
      }
      return;
    }

    // ── Full project export ───────────────────────────────────────────────
    setLoading(true);
    try {
      const entries = buildFileEntries(allFiles, true);
      const blob = await downloadZip(entries).blob();
      const zipName = `${baseName}.zip`;
      triggerDownload(blob, zipName);
      toast.success(
        `Exported "${zipName}" — ${allFiles.size} file${allFiles.size === 1 ? "" : "s"} + boilerplate`
      );
    } catch (err) {
      console.error("[ExportButton] full export failed", err);
      toast.error("Export failed. Please try again.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button
          variant="outline"
          size="sm"
          className="h-8 gap-1.5 text-xs"
          disabled={loading}
          aria-label="Export project as ZIP"
        >
          {loading ? (
            <Loader2 className="h-3.5 w-3.5 animate-spin" />
          ) : (
            <Package className="h-3.5 w-3.5" />
          )}
          Export
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="end" className="w-52">
        <DropdownMenuItem
          onSelect={() => handleExport("current")}
          disabled={loading}
          className="gap-2"
        >
          <Download className="h-3.5 w-3.5 text-muted-foreground" />
          Export current component
        </DropdownMenuItem>
        <DropdownMenuSeparator />
        <DropdownMenuItem
          onSelect={() => handleExport("full")}
          disabled={loading}
          className="gap-2"
        >
          <Package className="h-3.5 w-3.5 text-muted-foreground" />
          Export entire project
        </DropdownMenuItem>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}
